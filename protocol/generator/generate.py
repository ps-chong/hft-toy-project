"""Generate cross-language protocol contracts and deterministic test vectors.

Every output is a pure function of protocol/schema/*.yaml (JSON-compatible
YAML). `--check` fails when a checked-in output has drifted from the schema,
so C++, Rust, VHDL, the register documentation, and the golden vectors can
never disagree silently.
"""

from __future__ import annotations

import argparse
import hashlib
import json
import struct
import sys
from pathlib import Path
from typing import Any

ROOT = Path(__file__).resolve().parents[2]
SCHEMA_DIR = ROOT / "protocol" / "schema"

INTEGER_SIZES = {"u8": 1, "u16": 2, "u32": 4, "u64": 8}
LE_FORMATS = {"u8": "<B", "u16": "<H", "u32": "<I", "u64": "<Q"}
RUST_INTEGERS = {"u8": "u8", "u16": "u16", "u32": "u32", "u64": "u64"}
HEADER = "Generated by protocol/generator/generate.py. Do not edit."


def load(name: str) -> dict[str, Any]:
    return json.loads((SCHEMA_DIR / name).read_text(encoding="utf-8"))


def schema_digest() -> str:
    digest = hashlib.sha256()
    for path in sorted(SCHEMA_DIR.glob("*.yaml")):
        digest.update(path.name.encode())
        digest.update(path.read_bytes())
    return digest.hexdigest()


def rust_hex(value: str) -> str:
    digits = value.removeprefix("0x")
    groups: list[str] = []
    while digits:
        groups.append(digits[-4:])
        digits = digits[:-4]
    return "0x" + "_".join(reversed(groups))


def camel(name: str) -> str:
    return "".join(part.title() for part in name.split("_"))


def validate_record(name: str, record: dict[str, Any], size: int) -> None:
    """Fields must tile the record exactly and integers must be naturally
    aligned, so the C++ and Rust structs need no packing pragmas."""
    cursor = 0
    for field in record["fields"]:
        label = f"{name}.{field['name']}"
        if field["offset"] != cursor:
            raise ValueError(
                f"{label}: expected offset {cursor}, found {field['offset']}"
            )
        kind = field["type"]
        if kind in INTEGER_SIZES:
            if field["size"] != INTEGER_SIZES[kind]:
                raise ValueError(f"{label}: {kind} must be {INTEGER_SIZES[kind]} bytes")
            if field["offset"] % field["size"]:
                raise ValueError(f"{label}: {kind} is misaligned")
        elif kind == "u16_array":
            if field["size"] % 2 or field["offset"] % 2:
                raise ValueError(f"{label}: u16 arrays must be even-sized and aligned")
        elif kind not in {"ascii", "bytes"}:
            raise ValueError(f"{label}: unsupported type {kind}")
        cursor += field["size"]
    if cursor != size:
        raise ValueError(f"{name}: fields cover {cursor} of {size} bytes")


def ipc_records(ipc: dict[str, Any]) -> dict[str, dict[str, Any]]:
    records: dict[str, dict[str, Any]] = ipc["records"]
    for name, record in records.items():
        validate_record(name, record, ipc["record_size"])
    return records


# --------------------------------------------------------------------------- C++


def cpp_itch_namespace(itch: dict[str, Any]) -> str:
    lines = ["namespace itch {"]
    for field in itch["common_prefix"]:
        lines.append(
            f"inline constexpr std::size_t {field['name']}_offset = {field['offset']};"
        )
    for message in itch["messages"]:
        lines.append(f"namespace {message['name']} {{")
        lines.append(f"inline constexpr std::size_t length = {message['length']};")
        for field in message.get("fields", []):
            lines.append(
                f"inline constexpr std::size_t {field['name']}_offset = {field['offset']};"
            )
        lines.append(f"}}  // namespace {message['name']}")
    lines.append("}  // namespace itch")
    return "\n".join(lines)


def cpp_header(
    itch: dict[str, Any],
    mold: dict[str, Any],
    ipc: dict[str, Any],
    registers: dict[str, Any],
    telemetry: dict[str, Any],
    digest: str,
) -> str:
    message_lines = "\n".join(
        f"  {message['name']} = '{message['type']}'," for message in itch["messages"]
    )
    length_lines = "\n".join(
        f"inline constexpr std::size_t {message['name']}_length = {message['length']};"
        for message in itch["messages"]
    )
    ring_lines = "\n".join(
        f"inline constexpr std::size_t ring_{name} = {depth};"
        for name, depth in ipc["rings"].items()
    )
    mold_lines = "\n".join(
        f"inline constexpr std::size_t {field['name']}_offset = {field['offset']};"
        for field in mold["fields"]
    )
    flag_blocks: list[str] = []
    for record_name, record in ipc["records"].items():
        flags = record.get("flags")
        if not flags:
            continue
        constants = "\n".join(
            f"inline constexpr unsigned {name} = {bit}U;" for name, bit in flags.items()
        )
        flag_blocks.append(
            f"namespace {record_name}_flag {{\n{constants}\n}}  // namespace {record_name}_flag"
        )
    flag_lines = "\n\n".join(flag_blocks)
    register_lines = "\n".join(
        f"inline constexpr std::uintptr_t {register['name'].lower()} = "
        f"{register['offset']}U;"
        for register in registers["registers"]
    )
    return f"""// {HEADER}
#pragma once

#include <algorithm>
#include <array>
#include <bit>
#include <concepts>
#include <cstddef>
#include <cstdint>
#include <span>
#include <string_view>

namespace hft::protocol {{
inline constexpr std::uint16_t abi_version = {ipc["version"]};
inline constexpr std::size_t moldudp64_header_size = {mold["header_size"]};
inline constexpr std::size_t ipc_record_size = {ipc["record_size"]};
{ring_lines}
inline constexpr std::size_t telemetry_payload_size = {telemetry["payload_size"]};
inline constexpr std::uint16_t telemetry_source_port =
    {telemetry["default_source_port"]};
inline constexpr std::uint16_t telemetry_destination_port =
    {telemetry["default_destination_port"]};
inline constexpr std::string_view schema_sha256 = "{digest}";

enum class itch_type : std::uint8_t {{
{message_lines}
}};

{length_lines}

/// Network (big-endian) field to host integer. One byte-reverse instruction
/// on little-endian Arm; usable in constant expressions.
template <std::unsigned_integral T>
[[nodiscard]] constexpr auto read_be(std::span<std::byte const, sizeof(T)> bytes) noexcept
    -> T {{
  std::array<std::byte, sizeof(T)> raw{{}};
  std::ranges::copy(bytes, raw.begin());
  auto const value = std::bit_cast<T>(raw);
  if constexpr (std::endian::native == std::endian::little) {{
    return std::byteswap(value);
  }} else {{
    return value;
  }}
}}

{cpp_itch_namespace(itch)}

namespace mold {{
{mold_lines}
}}  // namespace mold

{flag_lines}

namespace reg {{
inline constexpr std::uintptr_t base = {registers["base_address"]}U;
{register_lines}
}}  // namespace reg
}}  // namespace hft::protocol
"""


def cpp_layout(ipc: dict[str, Any]) -> str:
    lines = [
        f"// {HEADER}",
        "//",
        "// Included at the end of hft/types.hpp, after the IPC structs exist: pins",
        "// every field offset and record size to protocol/schema/ipc.yaml.",
        "#pragma once",
        "",
        "#include <cstddef>",
        "",
    ]
    for name, record in ipc_records(ipc).items():
        cpp_type = f"::hft::{record['cpp_type']}"
        lines.append(f"// {name}")
        lines.append(
            f"static_assert(sizeof({cpp_type}) == {ipc['record_size']}, "
            f'"{name} must be one IPC record");'
        )
        for field in record["fields"]:
            lines.append(
                f"static_assert(offsetof({cpp_type}, {field['name']}) == {field['offset']}, "
                f'"{name}.{field["name"]} moved");'
            )
        lines.append("")
    return "\n".join(lines)


# -------------------------------------------------------------------------- Rust


def rust_encode_field(field: dict[str, Any]) -> str:
    offset, size, kind = field["offset"], field["size"], field["type"]
    name = field["name"]
    if "enum" in field:
        value = f"[self.{name} as u8]"
    elif kind in INTEGER_SIZES:
        value = f"self.{name}.to_le_bytes()"
    elif kind == "u16_array":
        value = f"super::u16_array_le(self.{name})"
    else:
        value = f"self.{name}"
    return f"        super::put::<{offset}, {size}>(&mut out, {value});"


def rust_decode_field(field: dict[str, Any]) -> str:
    offset, size, kind = field["offset"], field["size"], field["type"]
    name = field["name"]
    raw = f"super::take::<{offset}, {size}>(input)"
    if "enum" in field:
        return f"            {name}: super::{field['enum']}::try_from(u8::from_le_bytes({raw}))?,"
    if kind in INTEGER_SIZES:
        return f"            {name}: {RUST_INTEGERS[kind]}::from_le_bytes({raw}),"
    if kind == "u16_array":
        return f"            {name}: super::u16_array_from_le({raw}),"
    return f"            {name}: {raw},"


def rust_codec(ipc: dict[str, Any]) -> str:
    blocks: list[str] = []
    for name, record in ipc_records(ipc).items():
        rust_type = record["rust_type"]
        encode = "\n".join(rust_encode_field(field) for field in record["fields"])
        decode = "\n".join(rust_decode_field(field) for field in record["fields"])
        asserts = "\n".join(
            f"    assert!(core::mem::offset_of!(super::{rust_type}, {field['name']}) == "
            f"{field['offset']});"
            for field in record["fields"]
        )
        blocks.append(
            f"""impl super::{rust_type} {{
    /// Encodes the little-endian `{name}` IPC image ({record["direction"]}).
    #[must_use]
    pub fn encode_ipc(&self) -> [u8; IPC_RECORD_SIZE] {{
        let mut out = [0_u8; IPC_RECORD_SIZE];
{encode}
        out
    }}

    /// Decodes a `{name}` IPC image, rejecting unknown enum values.
    pub fn decode_ipc(input: &[u8]) -> Result<Self, super::ProtocolError> {{
        let input: &[u8; IPC_RECORD_SIZE] =
            input.try_into().map_err(|_| super::ProtocolError::InvalidLength)?;
        Ok(Self {{
{decode}
        }})
    }}
}}

const _: () = {{
    assert!(core::mem::size_of::<super::{rust_type}>() == IPC_RECORD_SIZE);
{asserts}
}};"""
        )
    return "\n\n".join(blocks)


def rust_itch_module(itch: dict[str, Any]) -> str:
    lines = ["pub mod itch {"]
    for field in itch["common_prefix"]:
        lines.append(
            f"    pub const {field['name'].upper()}: usize = {field['offset']};"
        )
    for message in itch["messages"]:
        lines.append(f"    pub mod {message['name']} {{")
        lines.append(f"        pub const LENGTH: usize = {message['length']};")
        for field in message.get("fields", []):
            lines.append(
                f"        pub const {field['name'].upper()}: usize = {field['offset']};"
            )
        lines.append("    }")
    lines.append("}")
    return "\n".join(lines)


def rust_ipc_module(ipc: dict[str, Any]) -> str:
    lines = ["pub mod ipc {"]
    for name, record in ipc_records(ipc).items():
        lines.append(f"    pub mod {name} {{")
        for field in record["fields"]:
            lines.append(
                f"        pub const {field['name'].upper()}: usize = {field['offset']};"
            )
        lines.append("    }")
    flag_types = {"normalized_event": "u32", "risk_config": "u16"}
    for record_name, record in ipc["records"].items():
        flags = record.get("flags")
        if not flags:
            continue
        lines.append(f"    pub mod {record_name}_flags {{")
        lines.extend(
            f"        pub const {flag.upper()}: {flag_types[record_name]} = 1 << {bit};"
            for flag, bit in flags.items()
        )
        lines.append("    }")
    lines.append("}")
    return "\n".join(lines)


def rust_module(
    itch: dict[str, Any],
    mold: dict[str, Any],
    ipc: dict[str, Any],
    registers: dict[str, Any],
    telemetry: dict[str, Any],
    digest: str,
) -> str:
    variants = "\n".join(
        f"    {camel(message['name'])} = b'{message['type']}',"
        for message in itch["messages"]
    )
    ring_lines = "\n".join(
        f"pub const RING_{name.upper()}: usize = {depth};"
        for name, depth in ipc["rings"].items()
    )
    mold_lines = "\n".join(
        f"    pub const {field['name'].upper()}: usize = {field['offset']};"
        for field in mold["fields"]
    )
    register_lines = "\n".join(
        f"    pub const {register['name']}: usize = {register['offset']};"
        for register in registers["registers"]
    )
    return f"""// {HEADER}
pub const ABI_VERSION: u16 = {ipc["version"]};
pub const MOLDUDP64_HEADER_SIZE: usize = {mold["header_size"]};
pub const IPC_RECORD_SIZE: usize = {ipc["record_size"]};
{ring_lines}
pub const TELEMETRY_PAYLOAD_SIZE: usize = {telemetry["payload_size"]};
pub const TELEMETRY_SOURCE_PORT: u16 = {telemetry["default_source_port"]};
pub const TELEMETRY_DESTINATION_PORT: u16 = {telemetry["default_destination_port"]};
pub const SCHEMA_SHA256: &str = "{digest}";

#[derive(Clone, Copy, Debug, Eq, PartialEq)]
#[repr(u8)]
pub enum ItchType {{
{variants}
}}

{rust_itch_module(itch)}

pub mod mold {{
{mold_lines}
}}

{rust_ipc_module(ipc)}

pub mod reg {{
    pub const BASE: usize = {rust_hex(registers["base_address"])};
{register_lines}
}}

{rust_codec(ipc)}
"""


# -------------------------------------------------------------------------- VHDL


def vhdl_package(
    itch: dict[str, Any],
    mold: dict[str, Any],
    ipc: dict[str, Any],
    registers: dict[str, Any],
    telemetry: dict[str, Any],
    digest: str,
) -> str:
    type_lines = "\n".join(
        f"  constant ITCH_{message['name'].upper()} : std_logic_vector(7 downto 0) "
        f':= x"{ord(message["type"]):02X}";'
        for message in itch["messages"]
    )
    offset_lines = [
        f"  constant ITCH_{field['name'].upper()}_OFFSET : natural := {field['offset']};"
        for field in itch["common_prefix"]
    ]
    for message in itch["messages"]:
        prefix = f"ITCH_{message['name'].upper()}"
        offset_lines.append(
            f"  constant {prefix}_LENGTH : natural := {message['length']};"
        )
        offset_lines.extend(
            f"  constant {prefix}_{field['name'].upper()}_OFFSET : natural := {field['offset']};"
            for field in message.get("fields", [])
        )
    mold_lines = "\n".join(
        f"  constant MOLD_{field['name'].upper()}_OFFSET : natural := {field['offset']};"
        for field in mold["fields"]
    )
    event_flags = ipc["records"]["normalized_event"].get("flags", {})
    mold_lines += "\n" + "\n".join(
        f"  constant EVENT_FLAG_{name.upper()}_BIT : natural := {bit};"
        for name, bit in event_flags.items()
    )
    register_lines: list[str] = []
    for register in registers["registers"]:
        register_lines.append(
            f"  constant REG_{register['name']} : natural := {int(register['offset'], 16)};"
        )
        register_lines.extend(
            f"  constant REG_{register['name']}_{bit_name.upper()}_BIT : natural := {bit};"
            for bit_name, bit in register.get("bits", {}).items()
        )
    return f"""-- {HEADER}
library ieee;
use ieee.std_logic_1164.all;
use ieee.numeric_std.all;

package hft_protocol_pkg is
  constant ABI_VERSION : natural := {ipc["version"]};
  constant MOLDUDP64_HEADER_SIZE : natural := {mold["header_size"]};
  constant IPC_RECORD_SIZE : natural := {ipc["record_size"]};
  constant TELEMETRY_PAYLOAD_SIZE : natural := {telemetry["payload_size"]};
  constant TELEMETRY_SOURCE_PORT : natural := {telemetry["default_source_port"]};
  constant TELEMETRY_DESTINATION_PORT : natural :=
    {telemetry["default_destination_port"]};
  constant SCHEMA_SHA256 : string := "{digest}";
{type_lines}
{chr(10).join(offset_lines)}
{mold_lines}
{chr(10).join(register_lines)}
end package;
"""


def register_markdown(registers: dict[str, Any], digest: str) -> str:
    rows = [
        "| Name | Offset | Access | Reset | Description |",
        "| --- | ---: | :---: | ---: | --- |",
    ]
    for register in registers["registers"]:
        bits = register.get("bits", {})
        bit_text = ", ".join(f"{name}={bit}" for name, bit in bits.items())
        description = register.get("description", "")
        if bit_text:
            description = f"{description} (bits: {bit_text})".strip()
        rows.append(
            f"| `{register['name']}` | `{register['offset']}` | "
            f"{register['access']} | `{register['reset']}` | {description} |"
        )
    return (
        "# Generated PL register map\n\n"
        f"Schema SHA-256: `{digest}`\n\n"
        f"Base address: `{registers['base_address']}`; span: `{registers['span']}`; "
        f"clock domain: `{registers['clock_domain']}`.\n\n"
        f"{registers['commit_semantics']}\n\n" + "\n".join(rows) + "\n"
    )


