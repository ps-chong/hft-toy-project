def itch_header(kind: str, locate: int, tracking: int, timestamp: int) -> bytes:
    return (
        kind.encode()
        + struct.pack(">HH", locate, tracking)
        + timestamp.to_bytes(6, "big")
    )


def itch_add_message() -> bytes:
    return b"".join(
        (
            itch_header("A", 1, 2, 123_456),
            struct.pack(">Q", 0x0102_0304_0506_0708),
            b"B",
            struct.pack(">I", 100),
            b"ACME    ",
            struct.pack(">I", 1_234_500),
        )
    )


def itch_cancel_message() -> bytes:
    return b"".join(
        (
            itch_header("X", 1, 3, 123_457),
            struct.pack(">Q", 0x0102_0304_0506_0708),
            struct.pack(">I", 25),
        )
    )


def itch_mixed_messages() -> list[bytes]:
    """One message of every type the pipeline decodes. Their lengths differ,
    so successive messages start at every byte lane of a 64-bit beat."""
    reference = 0x0102_0304_0506_0708
    return [
        itch_add_message(),
        itch_header("F", 1, 4, 123_458)
        + struct.pack(">Q", reference + 1)
        + b"S"
        + struct.pack(">I", 300)
        + b"ACME    "
        + struct.pack(">I", 1_234_600)
        + b"MPID",
        itch_header("E", 1, 5, 123_459) + struct.pack(">QIQ", reference, 10, 0xAA),
        itch_header("C", 1, 6, 123_460)
        + struct.pack(">QIQ", reference + 1, 20, 0xAB)
        + b"Y"
        + struct.pack(">I", 1_234_600),
        itch_cancel_message(),
        itch_header("U", 1, 7, 123_461)
        + struct.pack(">QQII", reference, reference + 2, 40, 1_234_400),
        itch_header("D", 1, 8, 123_462) + struct.pack(">Q", reference + 1),
    ]


def mold_packet(sequence: int, messages: list[bytes]) -> bytes:
    body = b"".join(struct.pack(">H", len(message)) + message for message in messages)
    return b"TESTSESS01" + struct.pack(">QH", sequence, len(messages)) + body


def telemetry_event_payload(telemetry: dict[str, Any], abi_version: int) -> bytes:
    return b"".join(
        (
            struct.pack(">HBBBBH", abi_version, 1, ord("A"), ord("B"), 0, 0),
            struct.pack(">Q", 1),
            struct.pack(">Q", 123_456),
            struct.pack(">Q", 0x0102_0304_0506_0708),
            b"ACME    ",
            struct.pack(">Q", 1_234_500),
            struct.pack(">I", 100),
            struct.pack(">I", 0),
            struct.pack(">Q", 0x10),
        )
    )[: telemetry["payload_size"]]


